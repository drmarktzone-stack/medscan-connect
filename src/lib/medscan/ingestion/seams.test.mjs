/**
 * בדיקות גילוי-תפר.
 *
 * לגלאי הזה שני צדדים, ושניהם מסוכנים:
 *
 * · **החמצה** — טקסט שמערבב שתי עמודות עובר לחילוץ, ומייצר ידע
 *   שמערבב שתי מחלות. הידע הזה יישא ציטוט-מקור אמיתי ויעבור כל
 *   שכבת הגנה, כי הציטוט באמת מופיע במסמך.
 *
 * · **החמרת-יתר** — טקסט תקין נחסם, והידע פשוט לא נכנס. זה הצד
 *   שקל לפספס, כי הוא נראה כמו בטיחות. כלל אחד שגוי («סוגר סוגריים
 *   ללא פותח») חסם 42% מהספר בעברית, שבה )טקסט( הוא הסדר הרגיל
 *   בחילוץ מ-PDF.
 *
 * לכן כל בדיקה כאן היא זוג: מקרה משובש אמיתי מהספר, ולצידו מקרה
 * נקי אמיתי שנראה דומה. גלאי שעובר רק את הצד האחד אינו תקין.
 */

import assert from 'node:assert';
import { detectSeams } from './extractionCore.js';

let pass = 0, fail = 0;
const test = (name, fn) => {
  try { fn(); pass += 1; console.log(`  ✓ ${name}`); }
  catch (e) { fail += 1; console.log(`  ✗ ${name}\n      ${e.message}`); }
};
const verdict = (text) => detectSeams(text).verdict;

console.log('\nגילוי תפר\n');

/* ── חייב לזהות: תפר אמיתי ─────────────────────────────────────────── */

test('שני תבליטים באותה שורה = שתי עמודות', () => {
  assert.strictEqual(verdict(
    '• UTI: • ניקור מתני טראומטי:\n' +
    'o הכי שכיח: o E.coli תא לבן אחד על כל 500 אריתרוציטים ב-CSF\n' +
    '• GDS ו-Enterococci בעיקר במומי שתן • CoNS ועוד מחוללים'
  ), 'corrupt');
});

test('תבליט אחרי טקסט עברי = שני שברי-עמודה שנתפרו', () => {
  // מקרה אמיתי מהספר. הגלאי הקודם החמיץ אותו: תבליט אחד בלבד בשורה.
  assert.strictEqual(verdict(
    '• viridans – במיוחד בהינתן הגיינה אורלית ירודה • פנאומוקוק – אם יש דלקת ריאות\n' +
    '• S.aureus בהינתן צנתר גופים זרים כוויות סוכרת • המופילוס אינפלואנזה\n' +
    '• GDS ו-Enterococci בעיקר במומי שתן ומניפולציות • CoNS'
  ), 'corrupt');
});

test('שורת-הוכחה בודדת בתא ארוך מספיקה', () => {
  // המקרה שהפיל את הגרסה מבוססת-השיעור: תא בן 46 שורות
  // שממזג שתי עמודות — רק 3 שורות נושאות סימן, כלומר 11%.
  const filler = Array.from({ length: 45 },
    (_, i) => `שורה קלינית תקינה מספר ${i} עם תוכן מספיק ארוך כדי להיספר`).join('\n');
  const merged = `${filler}\n• UTI: הגורמים השכיחים • ניקור מתני טראומטי ותיקון`;
  assert.strictEqual(verdict(merged), 'corrupt', 'שורת-הוכחה בודדת לא הכריעה');
});

test('סימון o אחרי מונח לטיני הוא סידור RTL, לא מיזוג', () => {
  // «o Early-onset (…)» נשמר כ-«Early-onset o (…)» בחילוץ מ-PDF.
  assert.strictEqual(verdict(
    'קליניקה:\n' +
    'Early-onset o (מתחת ל-5 ימים, בד"כ תוך 24-48 שעות) – צורה ספטיסמית\n' +
    'Late-onset o (מעל 5 ימים, בד"כ סביב 14 ימים) – צורה מנינגיאלית'
  ), 'clean');
});

test('עברית צמודה לעברית אחרי פיסוק', () => {
  assert.strictEqual(verdict(
    'מהתינוקות עד חודש עם חום:מרבית המקרים ע"ר UTI בקטרמיה ומנינגיטיס\n' +
    'הגורמים השכיחים ביותר הם:קלבסיאלה ואנטרוקוק בשכיחות נמוכה יותר\n' +
    'השכיחות של מנינגיטיס:קונקומיטנטי נמוכה מאד עד גיל 28 ימים'
  ), 'corrupt');
});

/* ── אסור לזהות: טקסט נקי שנראה חשוד ───────────────────────────────── */

test('סוגריים בסדר RTL אינם תפר', () => {
  // )טקסט( הוא הסדר הרגיל בעברית שחולצה מ-PDF. הכלל שחסם את זה
  // הפיל 42% מהספר, ודיווח על כך כהגנה שפעלה.
  assert.strictEqual(verdict(
    'המחלה הגלומרולרית הכרונית השכיחה ביותר בילדים ובמתבגרים)\n' +
    'בנים>בנות (1:2), גילאי 10-35 שנים עם קורלציה לשינויים גנטיים\n' +
    'מחלה אימונית: קומפלקסים אימונים עקב ריבוי IgA בסרום ובכליה'
  ), 'clean');
});

test('רשימת תבליטים רגילה אינה תפר', () => {
  assert.strictEqual(verdict(
    '• יכולות להיות מפורקות חלקית או מפורקות באופן מלא לגמרי\n' +
    '• ברגישות לחלב פרה יש לצרוך פורמולות מפורקות במלואן בילדים\n' +
    '• אלו אין לצרוך תמ"ל ע"ב סויה עקב רגישות-צולבת בין החלבונים'
  ), 'clean');
});

test('פסקה עם סוגריים תקינים אינה תפר', () => {
  assert.strictEqual(verdict(
    'העורקים הריאתיים יכולים לצאת יחד מצידו השמאלי ואז להתפצל (type I) או\n' +
    'ללא גזע משותף ישירות מהאאורטה, במיקומים שונים (type II, Type III).\n' +
    'בשני החדרים יש לחץ סיסטמי. לאחר הלידה PVR עדיין גבוה ולכן הזרימה מוגברת.'
  ), 'clean');
});

test('טבלה של ערכי ייחוס אינה תפר', () => {
  assert.strictEqual(verdict(
    'עד 60 ימים: 30 מ"ג/ד"ל בערך תקין ומעלה נחשב חריג\n' +
    '61-90 ימים: 71 מ"ג/ד"ל הוא הסף המקובל בספרות\n' +
    '29-90 ימים: 8 תאים/מ"מ מעוקב הוא הגבול העליון'
  ), 'clean');
});

/* ── התנהגות בקצוות ────────────────────────────────────────────────── */

test('טקסט ריק או קצר אינו מסומן', () => {
  assert.strictEqual(verdict(''), 'clean');
  assert.strictEqual(verdict(null), 'clean');
  assert.strictEqual(verdict('קצר'), 'clean');
});

test('רמז בודד בקטע ארוך אינו מפיל את הקטע', () => {
  // רמז נשקל לפי שיעור — בשונה משורת-הוכחה.
  const clean = Array.from({ length: 20 },
    (_, i) => `שורה תקינה מספר ${i} עם תוכן קליני מספיק ארוך כדי להיספר`).join('\n');
  assert.strictEqual(verdict(`${clean}\nהמחלה:מתבטאת בחום ובפריחה אופיינית בילדים`), 'clean');
});

test('המספר של שורות-ההוכחה מדווח בנפרד', () => {
  const r = detectSeams('הגורמים השכיחים ביילודים • ניקור מתני טראומטי ותיקון תאים');
  assert.strictEqual(r.proof_lines, 1);
  assert.strictEqual(r.verdict, 'corrupt');
});

test('הציון והשורות המסומנות מדווחים, לא רק פסק-דין', () => {
  const r = detectSeams('• א: • ב:\n• ג ד ה ו ז ח ט י כ ל מ נ • ס ע פ צ ק ר ש ת א ב');
  assert.ok(r.score > 0, 'אין ציון');
  assert.ok(r.lines.length > 0, 'לא דווחו שורות');
  assert.ok(r.lines[0].reasons.length > 0, 'לא דווחה סיבה');
});

console.log(`\n  ${pass} עברו, ${fail} נכשלו\n`);
process.exit(fail > 0 ? 1 : 0);
